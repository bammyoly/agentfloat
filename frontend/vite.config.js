import { defineConfig, createLogger } from "vite";
import react from "@vitejs/plugin-react";
import tailwindcss from "@tailwindcss/vite";

// ---------------------------------------------------------------------------
// Vite config
//
//   1. Binding + allowedHosts. `npm run dev` binds 127.0.0.1 so the URL you open
//      is a secure context; `npm run dev:lan` passes --host 0.0.0.0 for tunnels
//      and hosted previews, where allowedHosts must accept an unknown origin.
//   2. The /api and /paid proxies — the browser must NEVER reach the gateway by
//      localhost, and must never see the agent private key. All gateway calls
//      are relative and proxied server-side to 127.0.0.1:4022.
//   3. Tailwind v4 via its Vite plugin. There is no tailwind.config.js: v4 is
//      configured in CSS with @theme, and it scans sources automatically.
//   4. CJS_INTEROP below — the reason Privy crashed the browser. Read it before
//      touching optimizeDeps.
// ---------------------------------------------------------------------------

const GATEWAY_PORT = process.env.GATEWAY_PORT || "4022";

// ---------------------------------------------------------------------------
// PRIVY, THE X402 SDK, AND COMMONJS INTEROP
//
// @privy-io/react-auth ships ESM, but its dependency tree contains 26
// CommonJS-only files that a browser cannot load as modules. The first one you
// hit is a nested eventemitter3:
//
//   node_modules/@privy-io/react-auth/node_modules/eventemitter3/
//     index.mjs ->  import EventEmitter from './index.js'
//     index.js  ->  module.exports = EventEmitter      (pure CJS, no exports)
//
// Served raw, the browser evaluates index.mjs, follows it into index.js, and
// dies with:
//
//   Uncaught SyntaxError: The requested module '.../eventemitter3/index.js'
//   does not provide an export named 'default'
//
// Vite's esbuild pre-bundler is what supplies CJS->ESM interop, so any package
// listed in `optimizeDeps.exclude` loses it for its whole subtree.
//
// There are two ways out, and this file supports both:
//
//   DEFAULT — keep Privy excluded (cheap on RAM) but force esbuild to
//             pre-bundle every CommonJS package underneath it, listed
//             explicitly in CJS_INTEROP. Verified against the full 4,003-module
//             graph in a 2GB sandbox.
//
//   AGENTFLOAT_PREBUNDLE_PRIVY=1 — exclude nothing and let Vite pre-bundle the
//             whole tree, which is the standard, faster, upgrade-proof setup.
//             Needs roughly 4GB of free RAM; on a 2GB box esbuild gets
//             OOM-killed ("The service was stopped").
//
// CJS_INTEROP was generated by `npm run check:deps`, which crawls the served
// module graph and reports any raw CommonJS file it finds. Re-run it after
// bumping @privy-io/* or @x402/* — a new transitive CJS dep will not be in this
// list and will reproduce exactly the crash above.
// ---------------------------------------------------------------------------

/** package -> nested-dep entries, in Vite's "parent > child" form. */
const CJS_INTEROP = [
  "eventemitter3",
  "@walletconnect/utils > eventemitter3",
  "@walletconnect/window-getters",
  "@walletconnect/window-metadata",
  "@coinbase/wallet-sdk",
  "@reown/appkit > pino",
  "@reown/appkit-controllers > pino",
  "@reown/appkit-utils > pino",
  "@reown/appkit-ui > qrcode",
  "@reown/appkit-ui > qrcode/lib/browser",
  "@reown/appkit-ui > qrcode/lib/renderer/svg-tag",
  // The same qrcode, nested a second time under WalletConnect's ethereum
  // provider — added when the Reown connector was integrated. A nested copy is
  // a separate package as far as esbuild is concerned, so the appkit-ui entry
  // above does not cover it.
  "@walletconnect/ethereum-provider > qrcode",
  "@walletconnect/ethereum-provider > qrcode/lib/browser",
  "@walletconnect/ethereum-provider > qrcode/lib/renderer/svg-tag",
  "@privy-io/react-auth > eventemitter3",
  "blakejs",
  "canonicalize",
  "cross-fetch",
  "dayjs",
  // Vite resolves a bare `dayjs` from optimizeDeps.include but silently drops
  // the SUBPATH entries (dayjs/plugin/relativeTime and friends): dayjs 1.11 has
  // no `exports` map, so those specifiers are not resolvable at scan time and
  // keep being served as raw CJS. Including the *importer* instead makes esbuild
  // bundle the pair together, which does apply interop. Both forms are listed —
  // the subpaths are harmless when they resolve and essential when they do.
  "@reown/appkit-common",
  "@reown/appkit-common > dayjs/plugin/relativeTime",
  "@reown/appkit-common > dayjs/plugin/updateLocale",
  "@reown/appkit-common > dayjs/locale/en",
  "dayjs/locale/en",
  "dayjs/plugin/relativeTime",
  "dayjs/plugin/updateLocale",
  "events",
  "fetch-retry",
  "pino",
  "react-device-detect",
  "use-sync-external-store",
  "use-sync-external-store/with-selector",
];

const PREBUNDLE_PRIVY = !/^(0|false|no|off)$/i.test(process.env.AGENTFLOAT_PREBUNDLE_PRIVY || "");

// The packages that are lazily imported and drag in the heavy trees.
const HEAVY = ["@privy-io/react-auth", "@x402/fetch", "@x402/evm"];

const proxyToGateway = {
  target: `http://127.0.0.1:${GATEWAY_PORT}`,
  changeOrigin: true,
};

// ---------------------------------------------------------------------------
// LOG FILTER
//
// Vite warns once per file when a package publishes a sourcemap whose `sources`
// point at files that were not shipped. @privy-io/* and @reown/appkit* do this
// for roughly 300 files, and because those packages sit in `optimizeDeps.exclude`
// (see CJS_INTEROP above) Vite serves them raw and prints every single one.
//
// They are pure noise: nothing is broken, and there is nothing to fix, because
// the missing sources belong to a third party's build. Left alone they scroll
// real errors off the screen.
//
// BOTH `warn` AND `warnOnce` HAVE TO BE PATCHED. This one is emitted via
// `logger.warnOnce`, and in Vite's createLogger() that method calls an internal
// `output()` closure directly rather than going through `logger.warn` — so
// patching only `warn` silently filters nothing. The message is deduped per
// distinct string, and the string contains the file path, which is why it
// appears once per file rather than once overall.
//
// Everything else is passed through at full volume, and a single line is printed
// when the filter first engages so nothing disappears silently.
// `AGENTFLOAT_PREBUNDLE_PRIVY=1` removes these at the source by letting esbuild
// bundle those packages instead of serving them raw.
// ---------------------------------------------------------------------------
const logger = createLogger();
const NOISE = "points to missing source files";
let suppressed = 0;

function announceOnce() {
  if (suppressed !== 1) return;
  logger.hasWarned = true;
  console.log(
    `\x1b[33m[vite]\x1b[0m Suppressing "${NOISE}" warnings from third-party dist files\n` +
      `       (@privy-io/*, @reown/*). Harmless, and unavoidable while those packages are\n` +
      `       served raw. Set AGENTFLOAT_PREBUNDLE_PRIVY=1 to pre-bundle them instead and\n` +
      `       remove these entirely. All other warnings and errors are unaffected.\n`
  );
}

/** Shared filter for both entry points. Returns true if the message was dropped. */
function dropNoise(msg) {
  if (typeof msg !== "string" || !msg.includes(NOISE)) return false;
  suppressed += 1;
  announceOnce();
  return true;
}

const originalWarn = logger.warn.bind(logger);
const originalWarnOnce = logger.warnOnce.bind(logger);

logger.warn = (msg, options) => {
  if (dropNoise(msg)) return;
  originalWarn(msg, options);
};

logger.warnOnce = (msg, options) => {
  if (dropNoise(msg)) return;
  originalWarnOnce(msg, options);
};

export default defineConfig({
  customLogger: logger,
  plugins: [react(), tailwindcss()],

  optimizeDeps: PREBUNDLE_PRIVY
    ? { exclude: [], include: [] }
    : { exclude: HEAVY, include: CJS_INTEROP },

  server: {
    // 127.0.0.1 by default, NOT 0.0.0.0. Two reasons, and the first one bites
    // hard:
    //
    //   1. Browsers only expose WebCrypto (crypto.randomUUID, crypto.subtle) and
    //      injected wallet APIs in a SECURE CONTEXT — HTTPS, or http://localhost
    //      / 127.0.0.1. Binding 0.0.0.0 makes Vite print a "Network:" URL like
    //      http://192.168.1.x:5173, and opening that breaks Privy and wallet
    //      extensions with `crypto.randomUUID is not a function`. App.jsx also
    //      renders a banner when it detects this.
    //   2. The /api proxy reaches the gateway, which holds the agent key and can
    //      spend its float. Serving the dashboard on 0.0.0.0 hands that to
    //      anyone on the LAN.
    //
    // Set AGENTFLOAT_HOST=0.0.0.0 (or pass --host) only for tunnels/previews.
    host: process.env.AGENTFLOAT_HOST || "127.0.0.1",
    port: Number(process.env.PORT || 5173),
    strictPort: false,
    allowedHosts: true,
    proxy: {
      "/api": proxyToGateway,
      // The built-in x402 seller lives in the gateway. Proxying /paid lets a
      // human open the paywalled endpoint in a browser tab same-origin and see
      // the real 402 + payment requirements.
      "/paid": proxyToGateway,
    },
  },
  preview: {
    host: "0.0.0.0",
    port: 4173,
    allowedHosts: true,
  },
  build: {
    outDir: "dist",
    sourcemap: false,
  },
});
